import json
import logging
from typing import Any

from config import get_settings

logger = logging.getLogger("finchat.streaming")

try:
    from redis.asyncio import Redis, from_url as redis_from_url
    HAS_REDIS = True
except ImportError:
    Redis = None  # type: ignore[assignment,misc]
    redis_from_url = None  # type: ignore[assignment,misc]
    HAS_REDIS = False


class StreamEventPublisher:
    """
    Publishes streaming events (status updates, tool call notifications,
    and token chunks) to Redis Pub/Sub on channel `stream:{session_id}`.
    """

    def __init__(
        self,
        session_id: int,
        redis_url: str | None = None,
        redis_client: Any = None,
    ) -> None:
        self.session_id = session_id
        self.channel = f"stream:{session_id}"
        self.redis_url = redis_url or get_settings().redis_url
        self._redis = redis_client

    async def _get_client(self) -> Any:
        if self._redis is not None:
            return self._redis
        if HAS_REDIS and self.redis_url:
            try:
                self._redis = redis_from_url(self.redis_url, decode_responses=True)
                return self._redis
            except Exception as exc:
                logger.warning("Could not connect to Redis for streaming: %s", exc)
        return None

    async def publish_event(self, event: dict[str, Any]) -> None:
        """Publish an arbitrary event dictionary as JSON."""
        client = await self._get_client()
        if client is None:
            return

        try:
            payload = json.dumps(event)
            await client.publish(self.channel, payload)
        except Exception as exc:
            logger.debug("Failed to publish stream event to %s: %s", self.channel, exc)

    async def publish_status(
        self,
        stage: str,
        message: str,
        **extra: Any,
    ) -> None:
        """Publish a high-level agent progress state (e.g. PII check, intent classification)."""
        await self.publish_event(
            {
                "type": "status",
                "stage": stage,
                "message": message,
                **extra,
            }
        )

    async def publish_tool_start(
        self,
        tool_name: str,
        message: str | None = None,
        **extra: Any,
    ) -> None:
        """Publish a tool execution commencement notification."""
        await self.publish_event(
            {
                "type": "tool_call_start",
                "tool_name": tool_name,
                # The frontend maps tool_name to a user-friendly message.
                # The message field here is a server-side fallback only.
                "message": message or "Retrieving banking data...",
                **extra,
            }
        )

    async def publish_tool_end(
        self,
        tool_name: str,
        success: bool = True,
        error_message: str | None = None,
        **extra: Any,
    ) -> None:
        """Publish a tool execution completion notification."""
        await self.publish_event(
            {
                "type": "tool_call_end",
                "tool_name": tool_name,
                "success": success,
                "error_message": error_message,
                **extra,
            }
        )

    async def publish_token(self, token: str) -> None:
        """Publish a single token chunk as it is generated by the LLM."""
        if token:
            await self.publish_event(
                {
                    "type": "token",
                    "token": token,
                }
            )

    async def publish_done(
        self,
        reply: str,
        tools_called: list[str],
        intent: str,
        **extra: Any,
    ) -> None:
        """Publish final response completion."""
        await self.publish_event(
            {
                "type": "done",
                "reply": reply,
                "tools_called": tools_called,
                "intent": intent,
                **extra,
            }
        )

    async def publish_error(self, error: str) -> None:
        """Publish an error notification."""
        await self.publish_event(
            {
                "type": "error",
                "error": error,
            }
        )

    async def close(self) -> None:
        """Close connection if locally managed."""
        if self._redis is not None and hasattr(self._redis, "aclose"):
            try:
                await self._redis.aclose()
            except Exception:
                pass
            self._redis = None

